import numpy as np
from random import randint
from sklearn.utils import shuffle
from sklearn.preprocessing import MinMaxScaler

train_labels = []
train_samples = []

def create_data():
  for i in range(50):
    #5% younger side-effect=1
    random_younger = randint(13,64)
    train_samples.append(random_younger)
    train_labels.append(1)

    #5 older side-effect=0
    random_older = randint(65,100)
    train_samples.append(random_younger)
    train_labels.append(0)

  for i in range(1000):
    #95 younger side-effect=0
    random_younger = randint(13 ,64)
    train_samples.append(random_younger)
    train_labels.append(0)

    #95 older side-effect=1
    random_older = randint(65,100)
    train_samples.append(random_older)
    train_labels.append(1)

create_data()

train_labels = np.array(train_labels)
train_samples = np.array(train_samples)
train_labels, train_samples = shuffle(train_labels, train_samples)

scaler = MinMaxScaler(feature_range=(0,1))
scaled_train_samples = scaler.fit_transform(train_samples.reshape(-1,1))

import tensorflow as tf
from tensorflow import keras
from keras.models import Sequential
from keras.layers import Activation
from keras.layers import Input, Dense
from keras.optimizers import Adam

from keras.metrics import categorical_crossentropy

physical_devices = tf.config.experimental.list_physical_devices('GPU')
print("Num of GPU's Availabel: ", len(physical_devices))
tf.config.experimental.set_memory_growth(physical_devices[0], True)

model = Sequential([Input(shape=(1,)),
                    Dense(units=16,  activation='relu'),
                    Dense(units=32, activation='relu'),
                    Dense(units=2, activation='softmax')])

model.summary()

model.compile(optimizer=Adam(learning_rate=0.0001), loss='sparse_categorical_crossentropy', metrics=['accuracy'])
model.fit(x=scaled_train_samples, y=train_labels, batch_size=10, epochs=30, shuffle=True, verbose=1)

test_labels = []
